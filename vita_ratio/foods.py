_BY_ID = {item["id"]: item for item in FOODS}
_PUNCT = re.compile(r"[^\w\s\-]+", re.UNICODE)


def normalize(text: str) -> str:
    """Нижний регистр, ё→е, без пунктуации и лишних пробелов."""
    value = str(text or "").lower().replace("ё", "е")
    value = _PUNCT.sub(" ", value)
    return " ".join(value.split())


def all_items() -> list[dict]:
    return FOODS


def find_by_id(food_id: str) -> dict | None:
    return _BY_ID.get(str(food_id or "").strip())


def _tokens(text: str) -> set[str]:
    return {token for token in normalize(text).split() if len(token) > 1 or token.isdigit()}


def _score(item: dict, query: str) -> float:
    q = normalize(query)
    if not q:
        return 0.0
    names = [normalize(item["name"])] + [normalize(alias) for alias in item["syn"]]
    if q in names:
        return 100.0
    best = 0.0
    query_tokens = _tokens(q)
    for name in names:
        if name.startswith(q):
            best = max(best, 90.0 - min(20.0, len(name) - len(q)) * 0.2)
        elif q in name:
            best = max(best, 80.0)
        else:
            name_tokens = _tokens(name)
            if query_tokens and query_tokens <= name_tokens:
                best = max(best, 70.0 - min(15.0, len(name) - len(q)) * 0.2)
            elif query_tokens:
                overlap = len(query_tokens & name_tokens)
                if overlap:
                    best = max(best, 20.0 + 40.0 * overlap / len(query_tokens))
    return best


def search(query: str, limit: int = 8) -> list[dict]:
    """Поиск продуктов по названию/синонимам. Возвращает позиции с КБЖУ на 100 г."""
    q = normalize(query)
    if not q:
        return []
    scored = [(item, _score(item, q)) for item in FOODS]
    scored = [pair for pair in scored if pair[1] > 0]
    scored.sort(key=lambda pair: (-pair[1], len(pair[0]["name"])))
    return [_public(item) for item, _ in scored[: max(1, int(limit))]]


def best_match(query: str) -> dict | None:
    """Лучшее совпадение или None, если непонятно о чём речь."""
    found = search(query, limit=1)
    return found[0] if found else None


def _public(item: dict) -> dict:
    return {
        "id": item["id"],
        "name": item["name"],
        "kcal": item["kcal"],
        "protein": item["protein"],
        "fat": item["fat"],
        "carbs": item["carbs"],
        "category": item["category"],
        "unit": UNIT,
    }


def macros_for_grams(food: dict, grams: float) -> dict:
    """КБЖУ порции: пересчёт с 100 г, округление до целых ккал и 0.1 г."""
    portion = max(0.0, float(grams or 0))
    factor = portion / 100.0
    return {
        "title": food["name"],
        "food_key": food["id"],
        "grams": round(portion, 1),
        "kcal": int(round(food["kcal"] * factor)),
        "protein": round(food["protein"] * factor, 1),
        "fat": round(food["fat"] * factor, 1),
        "carbs": round(food["carbs"] * factor, 1),
    }
